/* ============================================
   DENTSCAN AI — report-generator.js
   Builds the inspection-report PDF entirely in the browser with jsPDF.
   No backend call required — analysis.js just calls generateReportPDF(result).

   Requires jsPDF to be loaded on the page first, e.g.:
   <script src="https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.2/jspdf.umd.min.js"></script>
   ============================================ */

(function (global) {
  'use strict';

  const SITE_URL   = 'dentscan.netlify.app';
  const BRAND_NAME = 'DentScan AI';

  const COLORS = {
    border:    [212, 219, 226], // light gray-blue frame
    header:    [20, 24, 31],    // near-black header bar (var(--ink))
    watermark: [229, 231, 236], // very light gray watermark
    danger:    [209, 69, 59],
    dangerSoft:[252, 240, 239],
    ok:        [26, 127, 90],
    okSoft:    [235, 245, 241],
    steel:     [61, 74, 92],
    steelSoft: [107, 118, 134],
    ink:       [20, 24, 31]
  };

  function mm(v) { return v; } // jsPDF is already in mm units for A4 below

  function drawBorder(doc, pageW, pageH) {
    const margin = 8;
    doc.setDrawColor(...COLORS.border);
    doc.setLineWidth(0.4);
    doc.rect(margin, margin, pageW - margin * 2, pageH - margin * 2);
  }

  function drawWatermark(doc, pageW, pageH, text) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(60);
    doc.setTextColor(...COLORS.watermark);
    // jsPDF text() angle is counter-clockwise degrees
    doc.text(text, pageW / 2, pageH / 2, { align: 'center', angle: 45 });
    // reset back to defaults so nothing downstream inherits the watermark styling
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(0, 0, 0);
  }

  function drawHeader(doc, pageW, timestamp) {
    const margin = 8;
    const headerH = 26;
    doc.setFillColor(...COLORS.header);
    doc.rect(margin, margin, pageW - margin * 2, headerH, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.text(`${BRAND_NAME} \u2014 Inspection Report`, margin + 8, margin + 12);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.text(`Generated: ${timestamp}`, margin + 8, margin + 19);

    return margin + headerH; // y position where body content can start
  }

  function drawFooter(doc, pageW, pageH, pageNum, totalPages) {
    const margin = 8;
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8.5);
    doc.setTextColor(...COLORS.steelSoft);
    doc.text(
      'Generated by DentScan AI \u2014 CNN-based vehicle damage classifier',
      margin + 8,
      pageH - margin - 12
    );

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(...COLORS.steelSoft);
    doc.text(
      `${BRAND_NAME} \u00b7 ${SITE_URL} \u00b7 Page ${pageNum} of ${totalPages}`,
      margin + 8,
      pageH - margin - 5
    );
  }

  /**
   * Generates and downloads the inspection report PDF.
   * @param {Object} result - { damaged, confidence, label, image (dataURL), timestamp (Date|string) }
   */
  function generateReportPDF(result) {
    if (!global.jspdf || !global.jspdf.jsPDF) {
      console.error('jsPDF not found. Include the jsPDF CDN script before report-generator.js.');
      throw new Error('jsPDF not loaded');
    }

    const { jsPDF } = global.jspdf;
    const doc = new jsPDF({ unit: 'mm', format: 'a4' });
    const pageW = doc.internal.pageSize.getWidth();
    const pageH = doc.internal.pageSize.getHeight();

    const isDamaged = !!result.damaged;
    const pct = Math.round((result.confidence || 0) * 100);
    const timestamp = result.timestamp instanceof Date
      ? result.timestamp.toISOString()
      : (result.timestamp || new Date().toISOString());

    // ── background layers ──
    drawBorder(doc, pageW, pageH);
    drawWatermark(doc, pageW, pageH, 'DENTSCAN');

    // ── header ──
    let y = drawHeader(doc, pageW, timestamp) + 14;
    const contentX = 20;

    // ── verdict ──
    const verdictColor = isDamaged ? COLORS.danger : COLORS.ok;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(20);
    doc.setTextColor(...verdictColor);
    doc.text(isDamaged ? 'DAMAGED' : 'NORMAL', contentX, y);
    y += 10;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(12);
    doc.setTextColor(...COLORS.ink);
    doc.text(`Confidence: ${pct}%`, contentX, y);
    y += 8;

    doc.setFontSize(11);
    doc.setTextColor(...COLORS.steel);
    const subLabel = result.label || (isDamaged ? 'Dent or scratch detected' : 'No visible damage detected');
    doc.text(subLabel, contentX, y);
    y += 12;

    // ── confidence bar ──
    const barX = contentX;
    const barW = pageW - contentX * 2;
    const barH = 4;
    doc.setDrawColor(...COLORS.border);
    doc.setFillColor(247, 248, 250);
    doc.roundedRect(barX, y, barW, barH, 1, 1, 'FD');
    doc.setFillColor(...verdictColor);
    const fillW = Math.max(2, (barW * pct) / 100);
    doc.roundedRect(barX, y, fillW, barH, 1, 1, 'F');
    y += 14;

    // ── scanned image, if provided ──
    if (result.image) {
      try {
        const imgProps = doc.getImageProperties(result.image);
        const maxW = pageW - contentX * 2;
        const maxH = 90;
        let w = maxW;
        let h = (imgProps.height / imgProps.width) * w;
        if (h > maxH) {
          h = maxH;
          w = (imgProps.width / imgProps.height) * h;
        }
        doc.setDrawColor(...COLORS.border);
        doc.rect(contentX - 1, y - 1, w + 2, h + 2);
        doc.addImage(result.image, contentX, y, w, h);
        y += h + 10;
      } catch (err) {
        console.warn('Could not embed scan image in report:', err);
      }
    }

    // ── footer ──
    drawFooter(doc, pageW, pageH, 1, 1);

    doc.save(`dentscan-report-${Date.now()}.pdf`);
  }

  global.DentScanReport = { generateReportPDF };

})(window);